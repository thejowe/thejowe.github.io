// Composición: carácter → [base, marca]. Las minúsculas i usan ı (sin punto).
const L = 7; // base inferior de la marca sobre minúsculas
const U = 9; // base inferior de la marca sobre mayúsculas
export const COMPOSE = {};
function add(marks, bases, kind) {
  const [chars, mark] = [marks, kind];
  bases.forEach((b, i) => {
    const ch = chars[i];
    if (!ch) return;
    const dotless = b === 'i' ? 'ı' : b;
    COMPOSE[ch] = { base: dotless, mark, y: b === b.toLowerCase() ? L : U };
  });
}
add('áéíóú', 'aeiou'.split(''), 'acute');
add('ÁÉÍÓÚ', 'AEIOU'.split(''), 'acute');
add('àèìòù', 'aeiou'.split(''), 'grave');
add('ÀÈÌÒÙ', 'AEIOU'.split(''), 'grave');
add('âêîôû', 'aeiou'.split(''), 'circ');
add('ÂÊÎÔÛ', 'AEIOU'.split(''), 'circ');
add('äëïöü', 'aeiou'.split(''), 'diaer');
add('ÄËÏÖÜ', 'AEIOU'.split(''), 'diaer');
COMPOSE['ñ'] = { base: 'n', mark: 'tilde', y: L };
COMPOSE['Ñ'] = { base: 'N', mark: 'tilde', y: U };
